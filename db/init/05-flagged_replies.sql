DROP TABLE IF EXISTS flagged_replies;

CREATE TABLE flagged_replies (
    id smallint generated by default as identity primary key,
    reply_id smallint NOT NULL REFERENCES replies(id) ON DELETE CASCADE,
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    flagged_at timestamp NOT NULL DEFAULT now(),
    reason text
);

CREATE INDEX idx_flagged_replies_comment_id ON flagged_replies(reply_id);
CREATE INDEX idx_flagged_replies_user_id ON flagged_replies(user_id);
